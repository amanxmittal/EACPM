#!/usr/bin/env node
/**
 * Extract selected UX4G component families out of the vendor bundle into a
 * committed stylesheet.
 *
 * Why this exists: `ux4g-web-components/styles/ux4g.css` is ~7.6MB, of which
 * ~94% is seven fonts embedded as base64 data-URIs. CLAUDE.md §8 forbids
 * shipping it raw, and PurgeCSS over it is fragile (the vendor uses
 * `[class*=spinner-]` substring selectors and bare state classes like
 * `.is-open` that naive purging drops). So we lift only the families we
 * actually use, into a file that is reviewable in git.
 *
 * Usage:  node scripts/extract-ux4g-components.mjs
 * Output: src/styles/ux4g-components.css
 *
 * To adopt another family, add it to FAMILIES and re-run. Verify the class
 * names against the vendor CSS first — the package README is unreliable
 * (it documents classes such as `ux4g-navbar-brand`, `ux4g-footer-content`
 * and `ux4g-skip-link` that do not exist in the CSS at all).
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const SRC = resolve(here, "../node_modules/ux4g-web-components/styles/ux4g.css");
const OUT = resolve(here, "../src/styles/ux4g-components.css");

/** Class-name prefixes to lift. A rule is kept when any class token in its
 *  selector equals one of these or starts with it followed by `-`. */
const FAMILIES = [
  // form controls
  "ux4g-input",
  "ux4g-textarea",
  "ux4g-form-group",
  // data display
  "ux4g-pagination",
  "ux4g-page-nav",
  "ux4g-avatar",
  "ux4g-breadcrumb",
  // feedback
  "ux4g-empty-state",
  // primitives
  "ux4g-divider",
  "ux4g-tag",
  "ux4g-search",
  // buttons — see DESIGN.md §9.2 for the pinned weight
  "ux4g-btn",
  "ux4g-icon-btn",
  // chips — choice; pill radius pinned in globals.css
  "ux4g-choice-chip",
  // typography — form labels; breadcrumb text rides the same shared rule (below)
  "ux4g-label",
];

const wanted = (token) =>
  FAMILIES.some((f) => token === f || token.startsWith(`${f}-`));

/**
 * True if a selector references any wanted family — as a `.class` token, or as
 * an `[class^=prefix-]` attribute selector. The latter matters: the vendor's
 * type engine (the rule turning `--ux4g-fs-current` etc. into real font-size/
 * weight/family) is written as
 *   .ux4g-text,[class^=ux4g-body-],[class^=ux4g-breadcrumb-],... { font-size: var(--ux4g-fs-current); ... }
 * — a `.class` regex alone never matches that, so any family relying on it
 * (breadcrumb, label, and heading/body/display/tab/title if adopted later)
 * would extract its per-size rules but silently lose the rule that actually
 * applies them.
 */
function selectorMatches(selector) {
  const classTokens = selector.match(/\.([A-Za-z0-9_-]+)/g) || [];
  const attrTokens = selector.match(/\[class\^=["']?([A-Za-z0-9_-]+?)-?\]/g) || [];
  return (
    classTokens.some((t) => wanted(t.slice(1))) ||
    attrTokens.some((t) => {
      const m = t.match(/\[class\^=["']?([A-Za-z0-9_-]+?)-?\]/);
      return m && wanted(m[1]);
    })
  );
}

/**
 * Walk the (minified, single-line) CSS and collect matching rules, recursing
 * into conditional at-rules so responsive variants are preserved. Operates on
 * a plain string so nested calls stay independent.
 */
function extract(css) {
  const rules = [];
  let i = 0;
  let prelude = "";

  while (i < css.length) {
    const ch = css[i];
    if (ch !== "{") {
      prelude += ch;
      i++;
      continue;
    }

    // Consume the balanced block body.
    const bodyStart = ++i;
    let depth = 1;
    while (i < css.length && depth > 0) {
      if (css[i] === "{") depth++;
      else if (css[i] === "}") depth--;
      if (depth > 0) i++;
    }
    const body = css.slice(bodyStart, i);
    i++; // step past the closing brace

    const head = prelude.trim();
    prelude = "";
    if (!head) continue;

    if (/^@(media|supports|layer|container)/i.test(head)) {
      // Keep the wrapper only if something inside survives.
      const inner = extract(body);
      if (inner.length) rules.push(`${head}{${inner.join("")}}`);
    } else if (/^@font-face/i.test(head) || body.includes("base64")) {
      // Never lift embedded fonts — self-hosted via next/font instead.
      continue;
    } else if (selectorMatches(head)) {
      rules.push(`${head}{${body}}`);
    }
  }
  return rules;
}

const css = readFileSync(SRC, "utf8");
const rules = extract(css);

const header = `/* UX4G Design System 3.0 — selected component families.
   GENERATED by scripts/extract-ux4g-components.mjs — do not edit by hand.
   Source: ux4g-web-components/styles/ux4g.css (fonts + unused families excluded).
   Families: ${FAMILIES.join(", ")}
   Themed via --ux4g-* tokens (see ux4g-tokens.css) and the bridge in globals.css. */\n`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, header + rules.join("\n") + "\n", "utf8");

const kb = (n) => `${(n / 1024).toFixed(1)} KB`;
console.log(`Read    ${SRC.split("/").slice(-3).join("/")}  ${kb(css.length)}`);
console.log(`Wrote   src/styles/ux4g-components.css  ${kb(header.length + rules.join("\n").length)}  (${rules.length} rules)`);
